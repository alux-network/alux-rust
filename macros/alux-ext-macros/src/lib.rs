/// Declares extension methods and optionally gives each method a first-order operation type.
///
/// Plain `defunc` produces a hidden `Op_<method><Context>` type, named by the method exactly as
/// written, implementing `OperationAlg` and `ApplyAlg`. When every method already builds first-order
/// route syntax from `routes()`, plain `defunc` names those inferred programs
/// directly. A backend such as `defunc(via = http)` or `defunc(via = jsonrpc)`
/// additionally lifts convenient method references while producing named programs
/// and their interpreter evidence.
///
/// Several backends are cumulative: `defunc(via = http, via = cli)` lowers the declarations each
/// backend recognizes by its root call (`routes()`, `methods()`, `commands()`, `record()`) into that
/// backend's programs, all in one extension. A bound on the block reaches every program in it, so
/// a mixed block states each transport's algebra on the declarations of that transport, as in
/// `fn status_api<Alg>(&self) where This: HttpRouteAlg`. A bound on `This` is what the program's
/// interpreter answers, so it reaches the program's interpretation and not the method that names
/// the program.
///
/// ```ignore
/// use alux_ext::ext;
///
/// #[ext(name = CounterExt, defunc)]
/// impl<This> This
/// where
///     This: CounterAlg,
/// {
///     async fn incremented(&self, by: u32) -> u32 {
///         self.increment(by).await
///     }
/// }
///
/// // The expansion also defines `Op_incremented<This>`.
/// ```
///
/// ```ignore
/// use alux_ext::ext;
/// use alux_http::http;
///
/// #[ext(name = StatusRoutesExt, defunc(via = http))]
/// impl<This> This
/// where
///     This: HttpRouteAlg,
/// {
///     /// Declares the status surface.
///     fn status_routes<Alg>(&self) {
///         self.routes().get("/status", self.op(Alg::status_current).json())
///     }
/// }
///
/// // The expansion also defines `Program_status_routes<Alg>`.
/// ```
#[proc_macro_attribute]
pub fn ext(attr: TokenStream, item: TokenStream) -> TokenStream {
    ext_internal(attr.into(), item.into()).unwrap_or_else(syn::Error::into_compile_error).into()
}

/// Lowers extension methods into named, composable HTTP programs.
///
/// This is the HTTP backend that `alux_ext::ext(..., defunc(via = http))` selects. `via = http`
/// resolves the name in the authoring scope, so a declaration imports it as `use alux_http::http`.
/// Applying the attribute directly means the same thing.
///
/// Each method becomes a first-order HTTP program. A route handler written with `op(...)` is replaced
/// by the operation type generated by `alux_ext::ext(defunc)`, its declared input roles and output
/// kind (`.json()`, `.out::<Kind>()`, and their wrappers) become one `HttpOperationAlg` bound on the
/// interpreter, and a call to another method of the same extension becomes a nested program.
///
/// ```ignore
/// use alux_ext::ext;
/// use alux_http::{HttpRouteAlg, http};
///
/// #[ext(name = StatusApiExt, defunc(via = http))]
/// impl<This> This
/// where
///     This: HttpRouteAlg,
/// {
///     /// Declares the status surface.
///     fn status_api<Alg>(&self) {
///         self.routes().get("/status", self.op(Alg::status_current).json())
///     }
/// }
///
/// // The expansion also defines `Program_status_api<Alg>`.
/// ```
#[proc_macro_attribute]
pub fn http(attr: TokenStream, item: TokenStream) -> TokenStream {
    http_program_defunc_internal(attr.into(), item.into()).unwrap_or_else(syn::Error::into_compile_error).into()
}

/// Lowers extension methods into named, composable JSON-RPC programs.
///
/// This is the JSON-RPC backend that `alux_ext::ext(..., defunc(via = jsonrpc))` selects. `via = jsonrpc`
/// resolves the name in the authoring scope, so a declaration imports it as `use alux_jsonrpc::jsonrpc`.
/// Applying the attribute directly means the same thing.
///
/// Each method becomes a first-order JSON-RPC program. A method handler written with `op(...)` is
/// replaced by the operation type generated by `alux_ext::ext(defunc)`, the operation's argument
/// product and output become bounds on the interpreter, `.named()` selects object decoding using the
/// authored argument names, and a call to another method of the same extension becomes a nested
/// program.
///
/// A `fallible` argument converts every declared method's error into a JSON-RPC protocol error, so
/// each declaration that does not say otherwise is read as `.fallible()`. This argument belongs to
/// the JSON-RPC backend; every other argument is read as `ext` reads it.
///
/// ```ignore
/// use alux_ext::ext;
/// use alux_jsonrpc::{JsonRpcApiAlg, jsonrpc};
///
/// #[ext(name = StatusRpcExt, defunc(via = jsonrpc))]
/// impl<This> This
/// where
///     This: JsonRpcApiAlg,
/// {
///     /// Declares the status surface.
///     fn status_rpc<Alg>(&self) {
///         self.methods().method("status_current", self.op(Alg::status_current))
///     }
/// }
///
/// // The expansion also defines `Program_status_rpc<Alg>`.
/// ```
#[proc_macro_attribute]
pub fn jsonrpc(attr: TokenStream, item: TokenStream) -> TokenStream {
    jsonrpc_program_defunc_internal(attr.into(), item.into()).unwrap_or_else(syn::Error::into_compile_error).into()
}

/// Lowers extension methods into named, composable shape programs.
///
/// This is the shape backend that `alux_ext::ext(..., defunc(via = shape))` selects. `via = shape`
/// resolves the name in the authoring scope, so a declaration imports it as `use alux_shape::shape`.
/// Applying the attribute directly means the same thing.
///
/// Each method becomes a first-order shape program named after the method, with a `_shape` suffix
/// dropped. An identifier in name position states the words that name a member, splitting on `_`; a
/// string literal there states a name no identifier spells. The record the declaration opens is named
/// and closed by the expansion, so no declaration writes a name for it, a closing call, or a return
/// type. A call to another method of the same extension becomes a nested program.
///
/// A shape body applies no handler — it reads the algebra through the same `self` the author wrote —
/// so the bounds the impl states are the whole requirement, and no per-member evidence is generated.
///
/// The expansion adds no imports, because a declaration's `use` list is the author's. So everything a
/// body reads must already be in scope: the algebra, and any extension the body derives its vocabulary
/// from — `ShapeTaggedExt` for a tagged encoding, whatever ext states a leaf vocabulary of its own.
/// `shape` itself must be in scope too, or `defunc(via = shape)` resolves to nothing: neither
/// attribute expands, the authored block reaches the compiler as written, and the errors read
/// `visibility qualifiers are not permitted here` on the `pub impl` followed by `cannot find value`
/// for every member name. Nothing in that points at the missing import.
///
/// ```ignore
/// use alux_ext::ext;
/// use alux_shape::{FieldAlg, ShapeAlg, shape};
///
/// #[ext(name = UserShapeExt, defunc(via = shape))]
/// pub impl<This> This
/// where
///     This: ShapeAlg + FieldAlg,
/// {
///     /// A user, as a surface answers one.
///     fn user_shape(&self) {
///         self.record().field(display_name, self.text()).field(email, self.opt(self.text()))
///     }
/// }
///
/// // The expansion also defines `Program_user_shape`.
/// ```
#[proc_macro_attribute]
pub fn shape(attr: TokenStream, item: TokenStream) -> TokenStream {
    shape_program_defunc_internal(attr.into(), item.into()).unwrap_or_else(syn::Error::into_compile_error).into()
}

/// Lowers extension methods into named, composable CLI programs.
///
/// This is the CLI backend that `alux_ext::ext(..., defunc(via = cli))` selects. `via = cli`
/// resolves the name in the authoring scope, so a declaration imports it as `use alux_cli::cli`.
/// Applying the attribute directly means the same thing.
///
